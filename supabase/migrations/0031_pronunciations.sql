-- 0031: 読み方辞書
--
-- 音声モデル(Gemini Live)は漢字・英数字の読みを文脈から推測するため、
-- 固有名詞(地名・人名・製品名)の発音が揺れることがある(実例:
-- 北上市→「ぼかみし」、BASE44→「ベースヨンヨン」)。発音辞書を渡す
-- APIが無い現状では、読みをシステム指示で明示するのが最も効く対策。
--
-- ブレインごとに「用語=よみ」を1行1組のテキストで保存し、会話開始時の
-- システム指示へ自動注入する。編集はブレイン画面の詳細設定から行う。
alter table avatars add column if not exists pronunciations text;

comment on column avatars.pronunciations is
  '読み方辞書。1行1組「用語=よみ」。会話開始時にシステム指示へ注入される';
